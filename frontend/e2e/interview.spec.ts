test('24 to 12 hour rule challenge and all dashboard filters affect API results (B)',async({page,request})=>{
  await page.goto('/')
  const settings=await (await request.get('/api/rules',{maxRetries:2,timeout:120000})).json()
  if(settings.dispatch_hours!==24){const reset=await request.put('/api/rules',{data:{...settings,dispatch_hours:24},timeout:120000});expect(reset.ok()).toBeTruthy()}
  const count24=(await (await request.get('/api/tasks?category=dispatch_delay&status=open')).json()).length
  await navigate(page,'Business rules')
  await page.getByLabel('Dispatch threshold',{exact:true}).fill('12')
  await page.getByRole('button',{name:'Save & reevaluate'}).click()
  await expect(page.getByRole('status').filter({hasText:'Rules saved.'})).toBeVisible()
  const count12=(await (await request.get('/api/tasks?category=dispatch_delay&status=open')).json()).length
  expect(count12).toBeGreaterThan(count24)
  await navigate(page,'Dashboard')
  const response=page.waitForResponse(r=>r.url().includes('/api/dashboard?')&&r.url().includes('category=dispatch_delay')&&r.ok())
  await page.getByLabel('Exception filter').selectOption('dispatch_delay')
  const filtered=await (await response).json()
  expect(filtered.open_tasks).toBe(count12)
  await expect(page.getByTestId('open-tasks')).toHaveText(String(count12))
  await page.getByLabel('Employee filter').selectOption('Meera Iyer')
  await expect(page.getByText('Refreshing from backend…')).toBeHidden()
  await page.getByLabel('Priority filter').selectOption('urgent')
  await expect(page.getByTestId('open-tasks')).toHaveText('0')
  await page.getByLabel('From date').fill('2099-01-01')
  await expect(page.getByTestId('attention-count')).toHaveText('0')
  const direct=await (await request.get('/api/dashboard?date_from=2099-01-01&category=dispatch_delay&employee=Meera%20Iyer&priority=urgent',{maxRetries:2,timeout:120000})).json()
  expect(direct.open_tasks).toBe(0)
})

test('overdue reassignment persists, status changes audit user and time (D, E)',async({page,request})=>{
  await page.goto('/')
  await page.getByLabel('Responsible user').fill('Live Interview Manager')
  const overdue=await (await request.get('/api/tasks?category=failed_delivery&overdue=true')).json()
  expect(overdue.length).toBeGreaterThan(0)
  const target=overdue[0]
  const owner=target.assigned_employee==='Priya Nair'?'Aarav Shah':'Priya Nair'
  await navigate(page,'Follow-up tasks')
  await page.getByLabel('Exception filter').selectOption('failed_delivery')
  await page.getByLabel('Search orders or customers').fill(target.order_id)
  await expect(page.getByRole('row').filter({hasText:target.order_id})).toHaveCount(1)
  await page.getByRole('row').filter({hasText:target.order_id}).getByRole('button',{name:'Manage'}).click()
  await page.getByLabel('Task assigned employee').selectOption(owner)
  await page.getByLabel('Task status',{exact:true}).selectOption('in_progress')
  await page.getByLabel('Change note').fill('Overdue handover during live interview')
  await page.getByRole('button',{name:'Save task changes'}).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await upload(page,'naturax_orders.csv')
  const after=await (await request.get('/api/tasks?category=failed_delivery')).json()
  const saved=after.find((t:{id:number})=>t.id===target.id)
  expect(saved.assigned_employee).toBe(owner)
  expect(saved.status).toBe('in_progress')
  await page.reload()
  await navigate(page,'Audit trail')
  await page.getByLabel('Audit order ID').fill(target.order_id)
  const auditResponse=page.waitForResponse(r=>r.url().includes('/api/audit?')&&r.url().includes('action=task_reassigned')&&r.ok())
  await page.getByLabel('Audit action').selectOption('task_reassigned')
  await auditResponse
  const auditRow=page.getByRole('row').filter({hasText:'Live Interview Manager'})
  await expect(auditRow).toHaveCount(1)
  await expect(auditRow).toContainText(owner)
  await expect(auditRow).toContainText('IST')
  await expect(auditRow).toContainText('was_overdue')
  await page.screenshot({path:'../artifacts/reassignment-audit.png',fullPage:true})
})

test('Excel upload, daily CSV download, team creation, order updates and responsive views',async({page,request})=>{
  const browserErrors:string[]=[]
  page.on('pageerror',e=>browserErrors.push(e.message))
  await page.goto('/')
  const before=(await (await request.get('/api/tasks')).json()).length
  await upload(page,'naturax_orders.xlsx')
  expect((await (await request.get('/api/tasks')).json()).length).toBe(before)
  await navigate(page,'Business rules')
  const employeeName=`Interview Specialist ${Date.now()}`
  await page.getByLabel('New employee name').fill(employeeName)
  await page.getByRole('button',{name:'Add employee'}).click()
  await expect(page.getByText(employeeName,{exact:true})).toBeVisible()
  await navigate(page,'Daily reports')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download daily CSV'}).click()
  const download=await downloadPromise
  expect(download.suggestedFilename()).toMatch(/naturax-daily-.*\.csv/)
  await download.saveAs('../artifacts/daily-report.csv')
  await upload(page,'order_update_delivered.csv')
  const target=await (await request.get('/api/tasks?search=NX-1003')).json()
  expect(target.length).toBeGreaterThan(0)
  expect(target.every((t:{status:string})=>t.status==='resolved')).toBeTruthy()
  await navigate(page,'Orders')
  await page.getByLabel('Search orders or customers').fill('NX-1003')
  await expect(page.getByRole('row').filter({hasText:'NX-1003'})).toContainText('delivered')
  await page.setViewportSize({width:390,height:844})
  await page.getByLabel('Open navigation').click()
  await navigate(page,'Dashboard')
  await expect(page.getByTestId('open-tasks')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.screenshot({path:'../artifacts/dashboard-mobile.png',fullPage:true})
  expect(browserErrors).toEqual([])
})
